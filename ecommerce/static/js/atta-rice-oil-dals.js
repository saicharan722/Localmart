/* ============================================================
   CART
   ============================================================ */

function getAttaRiceOilDalsCart() {

    try {

        const cart = JSON.parse(
            localStorage.getItem("localmartGroceryCart")
        );

        return Array.isArray(cart) ? cart : [];

    } catch (error) {

        return [];

    }

}


function saveAttaRiceOilDalsCart(cart) {

    localStorage.setItem(
        "localmartGroceryCart",
        JSON.stringify(cart)
    );

}


/* ============================================================
   WISHLIST
   ============================================================ */

function getAttaRiceOilDalsWishlist() {

    try {

        const list = JSON.parse(
            localStorage.getItem("localmartGroceryWishlist") || "[]"
        );
        return Array.isArray(list) ? list.map(item => {
            if (item && typeof item === "object") return item;
            return findAttaRiceOilDalsProduct(item) || {
                id: item, name: "Saved grocery product", category: "Grocery",
                price: 0, mrp: 0, image: "", quantity: 1
            };
        }) : [];

    } catch (error) {

        return [];

    }

}


function saveAttaRiceOilDalsWishlist(list) {

    localStorage.setItem(
        "localmartGroceryWishlist",
        JSON.stringify(list)
    );

}


/* ============================================================
   FIND PRODUCT
   IMPORTANT: SEARCH BOTH NORMAL + OIL PRODUCTS
   ============================================================ */

function findAttaRiceOilDalsProduct(productId) {

    return allAttaRiceOilDalsProducts.find(
        product =>
            String(product.id) ===
            String(productId)
    );

}


/* ============================================================
   GET CATEGORY PRODUCTS
   ============================================================ */

function getAttaRiceOilDalsCategoryProducts(category) {

    if (category === "all") {
        return allAttaRiceOilDalsProducts;
    }

    if (category === "atta") {
        return [
            ...zeptoAttaProducts,
            ...additionalAttaProducts
        ];
    }

    if (category === "oil") {
        return oilProducts;
    }

if (category === "ghee") {
        return [
            ...existingNonAttaProducts.filter(
                product =>
                    String(product.category || "").trim() === "Ghee"
            ),
            ...additionalGheeProducts
        ];
    }


if (category === "dal") {
        return [...zeptoDalProducts];
    }


if (category === "rice") {
        return [...zeptoRiceProducts];
    }

    const categories =
        attaRiceOilDalsCategoryMap[category];

    if (!categories) {
        return [];
    }

    return existingNonAttaProducts.filter(product =>
        categories.includes(
            String(product.category || "").trim()
        )
    );
}

/* ============================================================
   SEARCH CURRENT CATEGORY
   ============================================================ */

function getFilteredAttaRiceOilDalsProducts() {

    const categoryProducts =
        getAttaRiceOilDalsCategoryProducts(
            activeAttaRiceOilDalsCategory
        );


    const search =
        String(
            attaRiceOilDalsSearchTerm || ""
        )
            .trim()
            .toLowerCase();


    if (!search) {

        return [
            ...categoryProducts
        ];

    }


    return categoryProducts.filter(
        product => {

            const searchableText = [

                product.name,
                product.category,
                product.subcategory,
                product.unit,
                product.reviews

            ]
                .filter(Boolean)
                .join(" ")
                .toLowerCase();


            return searchableText.includes(
                search
            );

        }
    );

}


/* ============================================================
   ADD TO CART
   ============================================================ */

function addAttaRiceOilDalsProduct(productId) {

    const product =
        findAttaRiceOilDalsProduct(
            productId
        );


    if (!product) {

        console.error(
            "Product not found:",
            productId
        );

        return;

    }


    /* Use global cart if available */

    if (
        typeof window.addToCart === "function" &&
        window.addToCart !==
        addAttaRiceOilDalsProduct
    ) {

        window.addToCart(product);

        showAttaRiceOilDalsToast(
            `${product.name} added to cart`
        );

        updateAttaRiceOilDalsCartCount();

        return;

    }


    let cart =
        getAttaRiceOilDalsCart();


    const existing =
        cart.find(
            item =>
                String(item.id) ===
                String(product.id)
        );


    if (existing) {

        existing.quantity =
            Number(existing.quantity || 1) + 1;

    } else {

        cart.push({

            ...product,

            quantity: 1

        });

    }


    saveAttaRiceOilDalsCart(cart);


    renderAttaRiceOilDalsProducts(
        currentAttaRiceOilDalsProducts
    );


    updateAttaRiceOilDalsCartCount();


    showAttaRiceOilDalsToast(
        `${product.name} added to cart`
    );

}


/* ============================================================
   CHANGE QUANTITY
   ============================================================ */

function changeAttaRiceOilDalsQuantity(
    productId,
    change
) {

    let cart =
        getAttaRiceOilDalsCart();


    const item =
        cart.find(
            product =>
                String(product.id) ===
                String(productId)
        );


    if (!item) return;


    item.quantity =
        Number(item.quantity || 1) +
        Number(change);


    if (item.quantity <= 0) {

        cart =
            cart.filter(
                product =>
                    String(product.id) !==
                    String(productId)
            );

    }


    saveAttaRiceOilDalsCart(cart);


    renderAttaRiceOilDalsProducts(
        currentAttaRiceOilDalsProducts
    );


    updateAttaRiceOilDalsCartCount();

}


/* ============================================================
   GET QUANTITY
   ============================================================ */

function getAttaRiceOilDalsQuantity(productId) {

    const cart =
        getAttaRiceOilDalsCart();


    const item =
        cart.find(
            product =>
                String(product.id) ===
                String(productId)
        );


    return item
        ? Number(item.quantity || 1)
        : 0;

}


/* ============================================================
   WISHLIST
   ============================================================ */

function toggleAttaRiceOilDalsWishlist(
    productId
) {

    let wishlist =
        getAttaRiceOilDalsWishlist();


    const normalizedId =
        String(productId);


    const index =
        wishlist.findIndex(
            item =>
                String(typeof item === "object" ? item.id : item) ===
                normalizedId
        );


    if (index >= 0) {

        wishlist.splice(index, 1);

        showAttaRiceOilDalsToast(
            "Removed from wishlist"
        );

    } else {

        const product = findAttaRiceOilDalsProduct(productId);
        if (product) wishlist.push({ ...product, quantity: 1 });

        showAttaRiceOilDalsToast(
            "Added to wishlist ❤️"
        );

    }


    saveAttaRiceOilDalsWishlist(
        wishlist
    );


    renderAttaRiceOilDalsProducts(
        currentAttaRiceOilDalsProducts
    );

}


