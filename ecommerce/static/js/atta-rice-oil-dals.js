/* ============================================================
   SORT
   ============================================================ */

function sortAttaRiceOilDalsProducts(
    sortType
) {

    let products =
        getFilteredAttaRiceOilDalsProducts();


    switch (sortType) {


        case "price-low":

            products.sort(
                (a, b) =>
                    Number(a.price) -
                    Number(b.price)
            );

            break;


        case "price-high":

            products.sort(
                (a, b) =>
                    Number(b.price) -
                    Number(a.price)
            );

            break;


        case "rating":

            products.sort(
                (a, b) =>
                    Number(b.rating || 0) -
                    Number(a.rating || 0)
            );

            break;


        case "discount":

            products.sort(
                (a, b) => {

                    const discountA =
                        a.mrp
                            ? a.mrp - a.price
                            : Number(
                                a.discount || 0
                            );


                    const discountB =
                        b.mrp
                            ? b.mrp - b.price
                            : Number(
                                b.discount || 0
                            );


                    return discountB -
                        discountA;

                }
            );

            break;


        case "name":

            products.sort(
                (a, b) =>
                    a.name.localeCompare(
                        b.name
                    )
            );

            break;


        default:

            break;

    }


    currentAttaRiceOilDalsProducts =
        products;


    renderAttaRiceOilDalsProducts(
        products
    );

}


